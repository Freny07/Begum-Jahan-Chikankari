/**
 * Helper: find products for a collection
 */
export function getProductsByCollection(collectionHandle) {
  // Map collection handles to tag filters
  const tagMap = {
    'womens-wear': 'womens-wear',
    'mens-wear': 'mens-wear',
    'new-arrivals': 'new-arrival',
    'best-sellers': 'bestseller',
    'kurta-sets': 'kurta-sets',
    'anarkalis': 'anarkalis',
    'sarees': 'sarees',
    'dupattas': 'dupattas',
    'co-ord-sets': 'co-ord-sets',
    'sharara-sets': 'sharara-sets',
    'kurta-pajama': 'kurta-pajama',
    'nehru-jackets': 'nehru-jackets',
    'shirts': 'shirts',
    'all': null,
  };

  const tag = tagMap[collectionHandle];

  if (tag === null || tag === undefined) {
    return collectionHandle === 'all' ? MOCK_PRODUCTS : MOCK_PRODUCTS;
  }

  return MOCK_PRODUCTS.filter((p) => p.tags.includes(tag));
}

